INSERT INTO public.resource_files (
  id, resource_id, version_id, filename, file_type, mime_type, size_bytes, storage_path, is_previewable
)
SELECT
  ('82000000-0000-4000-8000-' || to_char(g, 'FM000000000000'))::uuid,
  r.id,
  v.id,
  CASE r.resource_type
    WHEN 'CAD' THEN 'assembly.stl'
    WHEN 'CODE' THEN 'ExampleTeleOp.java'
    WHEN 'TUTORIAL' THEN 'overview.md'
    WHEN 'MODEL' THEN 'model.json'
    ELSE 'overview.md'
  END,
  CASE r.resource_type
    WHEN 'CAD' THEN 'CAD'
    WHEN 'CODE' THEN 'SOURCE'
    WHEN 'TUTORIAL' THEN 'DOCUMENT'
    WHEN 'MODEL' THEN 'OTHER'
    ELSE 'DOCUMENT'
  END,
  CASE r.resource_type
    WHEN 'CAD' THEN 'model/stl'
    WHEN 'CODE' THEN 'text/x-java-source'
    WHEN 'MODEL' THEN 'application/json'
    ELSE 'text/markdown'
  END,
  CASE r.resource_type
    WHEN 'CAD' THEN 512
    ELSE 2048
  END,
  r.id::text || '/files/' || ('82000000-0000-4000-8000-' || to_char(g, 'FM000000000000')) || '/' ||
    CASE r.resource_type
      WHEN 'CAD' THEN 'assembly.stl'
      WHEN 'CODE' THEN 'ExampleTeleOp.java'
      WHEN 'TUTORIAL' THEN 'overview.md'
      WHEN 'MODEL' THEN 'model.json'
      ELSE 'overview.md'
    END,
  r.resource_type IN ('CAD', 'CODE', 'TUTORIAL', 'MODEL')
FROM generate_series(1, 32) AS g
JOIN public.resources r
  ON r.id = ('80000000-0000-4000-8000-' || to_char(g, 'FM000000000000'))::uuid
JOIN public.resource_versions v
  ON v.id = ('81000000-0000-4000-8000-' || to_char(g, 'FM000000000000'))::uuid
ON CONFLICT (id) DO NOTHING;

